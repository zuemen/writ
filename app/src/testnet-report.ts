/** 把 demo 的 timeline 轉成 docs/testnet.md（每步附 testnet explorer 連結）。 */
import { join } from "node:path";
import { writeFileSync } from "node:fs";
import { DEMO, ROOT, readJson } from "./near.js";
const t = readJson(join(DEMO, "timeline.json"));
const a = readJson(join(DEMO, "accounts.json"));
// 合約帳號上的鑰匙：不該有 full-access key，只有 agent 的 function-call key（撤銷後連這把都沒有）
const keysRes: any = await (await fetch(process.env.NEAR_RPC ?? "https://test.rpc.fastnear.com", {
  method: "POST", headers: { "content-type": "application/json" },
  body: JSON.stringify({ jsonrpc: "2.0", id: "1", method: "query", params: { request_type: "view_access_key_list", finality: "final", account_id: a.writ.id } }),
})).json();
const keys: any[] = keysRes.result?.keys ?? [];
const full = keys.filter((k) => k.access_key?.permission === "FullAccess").length;
const lines = [
  "# Writ on NEAR testnet", "",
  `Contract: [${a.writ.id}](https://testnet.nearblocks.io/address/${a.writ.id}) · generated by \`make testnet\` on ${new Date().toISOString().slice(0, 10)}`, "",
  `Access keys on the contract account now: ${keys.length}, full-access: ${full}. Check it yourself: \`near account list-keys ${a.writ.id} network-config testnet now\` or the RPC method \`view_access_key_list\`.`, "",
  "| step | what happened | transaction |", "|---|---|---|",
  ...t.map((e: any) => `| ${e.step} | ${e.line.replace(/\|/g, "\\|").replace(/\n/g, " ")} | ${e.hash ? `[${e.hash.slice(0, 10)}…](https://testnet.nearblocks.io/txns/${e.hash})` : "—"} |`),
];
writeFileSync(join(ROOT, "docs/testnet.md"), lines.join("\n") + "\n");
console.log("wrote docs/testnet.md");
