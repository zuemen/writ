/**
 * make testnet-usdc: run one real payment with Circle's official testnet USDC (not a mock token).
 * Precondition: the legal entity account (acme in accounts.json) has received test USDC from https://faucet.circle.com.
 * Results are written to docs/testnet-usdc.md.
 */
import { rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { teraToGas } from "near-api-js";
import { DEMO, NEAR, ROOT, as, call, view } from "./near.js";
import { A, pay, register } from "./flow.js";
import { py } from "./keri.js";

// https://developers.circle.com/stablecoins/usdc-contract-addresses (NEAR testnet)
const USDC = "3e2210e1184b45b64c8a434c0a7e7b23cc04ea7eb7a6c3c32520d03d4afcb8af";
const UNIT = 100_000n; // 0.1 USDC (6 decimals)
const a = A();
const acme = as(a.acme.id, a.acme.sk);
const usdc = (id: string) => view(USDC, "ft_balance_of", { account_id: id }) as Promise<string>;

const have = BigInt(await usdc(a.acme.id));
if (have < 4n * 10n * UNIT) {
  console.error(`${a.acme.id} holds ${have} of USDC's smallest unit. Get testnet USDC from https://faucet.circle.com (network: NEAR Testnet), then run this again.`);
  process.exit(2);
}

// The contract and the merchant must register with the token first, or receiving will fail
for (const id of [a.writ.id, a.merchant.id]) {
  const r = await call(acme, USDC, "storage_deposit", { account_id: id, registration_only: true }, { deposit: NEAR("0.01"), gas: teraToGas("30") });
  if (r.error) throw new Error(`storage_deposit ${id}: ${r.error}`);
}

for (const d of ["keri/.keystore", "keri/bundle", "keri/registrar"]) rmSync(join(ROOT, d), { recursive: true, force: true });
const init = py("issuer.py", "init", "--scope", a.merchant.id, "--rail", a.acme.id, "--n", "50", "--unit", String(UNIT), "--daily", "20", "--days", "30", "--asset", USDC);
py("verify.py", "pin", "--root", JSON.parse(init.slice(init.indexOf("{"), init.lastIndexOf("}") + 1)).root);

const reg = await register("0.5");
if (!reg.ok) throw new Error("register failed: " + reg.error);
const fund = await call(acme, USDC, "ft_transfer_call", { receiver_id: a.writ.id, amount: (4n * 10n * UNIT).toString(), msg: String(reg.cell) }, { deposit: 1n, gas: teraToGas("100") });
if (fund.error) throw new Error("funding failed: " + fund.error);

const before = BigInt(await usdc(a.merchant.id));
const paid = await pay(reg.cell, 1, a.merchant.id, "INV-USDC-1");
const received = BigInt(await usdc(a.merchant.id)) - before;
const attackerBefore = BigInt(await usdc(a.attacker.id));
const injected = await pay(reg.cell, 1, a.attacker.id, "INV-USDC-2");
const attackerGain = BigInt(await usdc(a.attacker.id)) - attackerBefore;
const ok = !!paid.value?.Paid && received === UNIT && injected.value?.Rejected?.reason === "SCOPE" && attackerGain === 0n;

const tx = (h?: string) => (h ? `[${h.slice(0, 10)}…](https://testnet.nearblocks.io/txns/${h})` : "—");
writeFileSync(join(ROOT, "docs/testnet-usdc.md"), [
  "# Real testnet USDC payment", "",
  `Token: Circle's testnet USDC, \`${USDC}\`. Contract: \`${a.writ.id}\`. Generated by \`make testnet-usdc\` on ${new Date().toISOString().slice(0, 10)}.`, "",
  "| step | result | transaction |", "|---|---|---|",
  `| open a token cell | cell #${reg.cell} | ${tx(reg.hash)} |`,
  `| fund it with 5 USDC via \`ft_transfer_call\` | vault funded | ${tx(fund.hash)} |`,
  `| agent pays 0.1 USDC to the in-scope merchant | merchant received ${received} of the smallest unit | ${tx(paid.hash)} |`,
  `| injected payment to an attacker | ${JSON.stringify(injected.value)}; attacker gained ${attackerGain} | ${tx(injected.hash)} |`, "",
].join("\n"));
console.log(`USDC_RESULT|${ok ? "PASS" : "FAIL"}|merchant_received=${received}|attacker_gain=${attackerGain}`);
void DEMO;
process.exit(ok ? 0 : 1);
